using Image=std::vector<std::uint8_t>;
void put(Image& image,unsigned address,unsigned value,unsigned width=4){
 const auto offset=address-0x400000u;
 if(address<0x400000u||offset+width>image.size())throw std::out_of_range("Native Retail data address");
 for(unsigned i=0;i<width;++i)image[offset+i]=std::uint8_t(value>>(i*8));
}
void parameters(Image& image,unsigned address,std::initializer_list<unsigned> values){
 for(auto value:values){put(image,address,value);address+=4;}
}
void caption(Image& image,unsigned address,std::string_view text){
 for(auto value:text)put(image,address++,static_cast<unsigned char>(value),1);
 put(image,address,0,1);
}
struct SampleDefinition{unsigned address,sample_id,period,length,sample_offset;};
void sample(Image& image,const SampleDefinition& s){put(image,s.address,s.sample_id);put(image,s.address+4,s.period);put(image,s.address+8,64);put(image,s.address+12,s.length);put(image,s.address+16,s.sample_offset);}
struct LampDefinition{unsigned address;int x,y,width_words,height;};
void lamp(Image& image,const LampDefinition& l){put(image,l.address,unsigned(l.x),2);put(image,l.address+2,unsigned(l.y),2);put(image,l.address+4,unsigned(l.width_words),2);put(image,l.address+6,unsigned(l.height),2);}
