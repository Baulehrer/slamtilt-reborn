#!/usr/bin/env python3
"""Verify the bounded Mean first-tick tracker resampling difference.

The original probe initializes explicit synthetic mixer state, uses music volume
64 and renders one 882-frame window without SFX or DirectSound. This does not
prove live game startup, device timing, tracker effects, loops, or later ticks.
Private original data/PCM and the reconstructed module remain under --work;
the report contains only derived numbers, hashes and bounded model checks.
"""
import argparse
import hashlib
import json
import math
import struct
import subprocess
import sys
from pathlib import Path

from extract_mean_stim import extract
from verify_retail_tracker_pcm import EXE_SHA, GAME, TABLES

ROOT = Path(__file__).resolve().parents[1]
FRAMES = 882


def sha(data):
    return hashlib.sha256(data).hexdigest()


def correlation(a, b):
    energy = sum(x * x for x in a) * sum(x * x for x in b)
    assert energy > 0
    return sum(x * y for x, y in zip(a, b)) / math.sqrt(energy)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--native', type=Path, default=ROOT / 'build/native/stim_audio_probe')
    p.add_argument('--exe', type=Path, default=GAME / 'SLAMTILT.EXE')
    p.add_argument('--dat', type=Path, default=GAME / 'DAT/MEAN.DAT')
    p.add_argument('--work', type=Path, default=ROOT / 'build/retail-tracker-phase')
    p.add_argument('--report', type=Path)
    args = p.parse_args()
    expected_dat, bank, order = TABLES['mean']
    executable, dat = args.exe.read_bytes(), args.dat.read_bytes()
    assert sha(executable) == EXE_SHA and sha(dat) == expected_dat, 'unsupported input'
    args.work.mkdir(parents=True, exist_ok=True)
    subprocess.run([sys.executable, str(ROOT / 'tools/verify_retail_tracker_pcm.py'),
                    '--table', 'mean', '--exe', str(args.exe), '--dat', str(args.dat),
                    '--output', str(args.work)], check=True)
    original_report = json.loads((args.work / 'mean-report.json').read_text())
    original_pcm = (args.work / 'mean-first-tick.s16le').read_bytes()
    assert original_report['exe_sha256'] == EXE_SHA
    assert original_report['dat_sha256'] == expected_dat
    assert sha(original_pcm) == original_report['pcm_sha256']
    original = struct.unpack(f'<{2 * FRAMES}h', original_pcm)
    assert original[::2] == original[1::2]
    original = original[::2]

    channels = original_report['channels']
    active = [row for row in channels if row[0] == 1]
    assert len(active) == 1
    _, address, length, loop_start, loop_length, period, volume, _ = active[0]
    offset = address - 0x1100000
    assert (offset, length, period, volume) == (0x84, 6466, 214, 64)
    source = struct.unpack(f'<{length}b', dat[offset:offset + length])
    freq = 0x361f0f // period
    step_q32 = ((freq << 32) // 44100) & ~15
    floor_indices = [(frame * step_q32) >> 32 for frame in range(FRAMES)]
    gain = 0x20000 // 6
    # This is the LUT table generated by the independently executed 0x44b640.
    original_model = [source[index] * gain * 127 // 65536 for index in floor_indices]
    assert list(original) == original_model, 'original PCM differs from floor/LUT model'

    stim, _ = extract(dat, 0, (bank,))
    stim_path = args.work / 'mean-bank0.stim'
    stim_path.write_bytes(stim)
    native_pcm = subprocess.check_output([str(args.native.resolve()), str(stim_path),
                                          str(FRAMES), str(FRAMES), 'restart',
                                          str(order), 'retail'])
    assert len(native_pcm) == FRAMES * 4
    native = struct.unpack(f'<{2 * FRAMES}h', native_pcm)
    assert native[::2] == native[1::2]
    native = native[::2]
    # libxmp's PAL C4 rate is 8287, C4 period 428, and its nearest mixer
    # operates in 16.16 steps with a half-sample offset. This is a model of
    # this specific note; it is not a claim about all libxmp instruments.
    xmp_step_q16 = (428 * 8287 * 65536) // (period * 44100)
    nearest_indices = [(32768 + frame * xmp_step_q16) >> 16 for frame in range(FRAMES)]
    floor_model = [source[index] for index in floor_indices]
    nearest_model = [source[index] for index in nearest_indices]
    floor_corr = correlation(floor_model, native)
    nearest_corr = correlation(nearest_model, native)
    assert 0.60 < floor_corr < 0.70 and nearest_corr > 0.99999
    mismatched_indices = sum(x != y for x, y in zip(floor_indices, nearest_indices))
    assert mismatched_indices > 400

    report = {'status': 'VERIFIED_BOUNDED', 'scope': __doc__,
              'exe_sha256': EXE_SHA, 'dat_sha256': expected_dat,
              'native_probe_sha256': sha(args.native.read_bytes()),
              'table': 'mean', 'bank': 0, 'order': order, 'frames': FRAMES,
              'original_executed_blocks': original_report['executed_original_blocks'],
              'original_pcm_sha256': sha(original_pcm), 'native_pcm_sha256': sha(native_pcm),
              'sample_dat_offset': hex(offset), 'sample_length': length,
              'sample_loop_start': loop_start, 'sample_loop_length': loop_length,
              'sample_period': period, 'sample_frequency_integer_hz': freq,
              'original_gain_factor': gain, 'original_gain_coefficient': 127,
              'original_exact_floor_lut_frames': FRAMES,
              'libxmp_nearest_step_q16': xmp_step_q16,
              'floor_vs_nearest_different_indices': mismatched_indices,
              'native_vs_floor_sample_correlation': round(floor_corr, 9),
              'native_vs_nearest_sample_correlation': round(nearest_corr, 9),
              'limits': ['One active Mean tracker voice, first tick only',
                         'Synthetic original mixer initialization and 882-frame window',
                         'Other notes, effects, loops, music changes and live timing untested',
                         'Correlation does not prove native PCM sample equality']}
    destination = args.report or args.work / 'phase-report.json'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(report, indent=2) + '\n')
    print(f'PASS: {FRAMES} original floor/LUT frames; native nearest correlation {nearest_corr:.9f}')


if __name__ == '__main__':
    main()
