def decode(b,start,end):
 out=bytearray();at=start
 while len(out)<480:
  if at>=end:raise ValueError()
  c=b[at];at+=1;n=max(c&127,1);n=min(n,480-len(out))
  if c&128:out.extend(bytes(n))
  else:
   if at+n>end:raise ValueError()
   out.extend(b[at:at+n]);at+=n
 return bytes(out),at
rows={}
for table in ['Mean','Pirate','Space','Demon']:
 b=(ROOT/f'build/decoded/full/{table}.Bin').read_bytes();pc=(PC/(table.upper()+'.DAT')).read_bytes();banks=[];matched=0;frames=0
 for at in range(len(b)-12):
  n=struct.unpack_from('>I',b,at)[0]
  if n<4 or n>1024 or n%4:continue
  count=n//4
  if at+n>=len(b):continue
  offsets=struct.unpack_from('>'+str(count)+'I',b,at)
  if any(x< n or x>len(b)-at for x in offsets) or any(x>=y for x,y in zip(offsets,offsets[1:])):continue
  found=[]
  try:
   for i,o in enumerate(offsets):
    end=at+offsets[i+1] if i+1<count else min(len(b),at+o+961)
    f,e=decode(b,at+o,end);target=pc.find(f)
    if target>=0 and len(set(f))>3:
     while target>=0:
      found.append({'index':i,'target':target,'source':at+o,'end':e})
      target=pc.find(f,target+1)
  except ValueError:continue
