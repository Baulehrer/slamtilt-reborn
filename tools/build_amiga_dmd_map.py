  selected.append((base,directory,count))
  offsets=struct.unpack_from('>7I',b,directory)
  for i,o in enumerate(offsets):
   f,_=decode(b,directory+o,directory+offsets[i+1]if i+1<count else len(b))
   mapped.add(base+480*i)
